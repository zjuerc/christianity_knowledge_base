#!/usr/bin/env python3
"""Package and verify an existing KB bundle. Never ingest PDFs or rebuild data."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import zipfile
from datetime import date
from pathlib import Path, PurePosixPath

import page_locations

SUPPORT_FILES = {
    "author_registry.json", "author_attribution_reviews.jsonl",
    "term_requests.json", "term_discovery_anchors.json",
}
RELEASE_README = "KB_RELEASE_README.md"
EXCLUDED = [
    "_source_cache/", "_pagination_cache/", "dated audit folders", "original PDFs",
    "Python source code", "temporary files", "backups", "audit reports",
    "SQLite databases", "application installers",
]
SOURCE_DATE_FIELDS = ("schema_version", "builder_version", "generated_at", "counts")


def read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def digest_stream(stream):
    digest = hashlib.sha256()
    for chunk in iter(lambda: stream.read(1024 * 1024), b""):
        digest.update(chunk)
    return digest.hexdigest()


def digest_file(path):
    with Path(path).open("rb") as stream:
        return digest_stream(stream)


def safe_name(name):
    """This release format has flat, portable, data-only member names."""
    if (not isinstance(name, str) or not name or "\\" in name or ":" in name
            or PurePosixPath(name).name != name or name in {".", ".."}
            or PurePosixPath(name).is_absolute()):
        raise ValueError(f"Unsafe or nested archive member: {name!r}")
    if name == RELEASE_README or name in SUPPORT_FILES:
        return name
    if not name.startswith("christian_kb_") or Path(name).suffix not in {".json", ".jsonl", ".csv", ".md"}:
        raise ValueError(f"Not a supported KB data file: {name!r}")
    if any(token in name.casefold() for token in (".before", ".backup", ".tmp", "release_manifest")):
        raise ValueError(f"Backup/temporary member rejected: {name!r}")
    return name


def select_files(kb_dir, manifest):
    names = {"christian_kb_manifest.json", "christian_kb_manifest.md", *SUPPORT_FILES}
    if not isinstance(manifest.get("files"), dict):
        raise ValueError("Existing KB file manifest required")
    for group in manifest["files"].values():
        if not isinstance(group, list):
            raise ValueError("Manifest file groups must be lists")
        names.update(safe_name(name) for name in group)
    if RELEASE_README in names:
        raise ValueError("The release README is generated by the packager")
    for name in names:
        safe_name(name)
        path = kb_dir / name
        if not path.is_file():
            raise FileNotFoundError(f"Required release file is missing: {name}")
        if path.is_symlink() or path.resolve().parent != kb_dir.resolve():
            raise ValueError(f"Release file resolves outside the KB directory: {name}")
    return sorted(names)


def previous_release(release_dir, release_date):
    candidates = []
    for path in release_dir.glob("christian_kb_*_release_manifest.json"):
        data = read_json(path)
        if data.get("release_date", "") < release_date:
            candidates.append((data["release_date"], path, data))
    return max(candidates, key=lambda item: item[0]) if candidates else None


def release_readme(release_date, manifest):
    counts, pagination = manifest["counts"], manifest["pagination"]
    coverage = pagination["coverage"]
    return f"""# Christian Theology Knowledge Base Release

Release packaging date: {release_date}
Evidence snapshot generated at: {manifest['generated_at']}

This data-only archive contains the complete generated KB bundle: primary,
extended, and archival evidence; page and section metadata; author attribution;
Scripture and term concordances; source registries; and cross-book links.
It covers {counts['sources']:,} sources and {counts['pages']:,} PDF file pages.

## Extraction and use

Extract all files together into a knowledge-base data directory, keeping their
names unchanged. To use the standalone KB search tools, extract into a checkout
of the knowledge-base source repository. Python source and its dependencies are
distributed separately. The manifest lists every generated data file required
by KB search and Theologia Search's index builder.

An existing Theologia Search index can import pagination using the application's
pagination updater. That metadata-only migration requires a compatible existing
index. For a new index, use Theologia Search's documented index-building command.
No original PDFs or private caches are needed to search this bundle or build an
index from it. The Theologia Search desktop installer is distributed separately.

## Page references

The independently versioned `christian_kb_page_locations.jsonl` extension keeps:

- **PDF file page:** The 1-based PDF position, including covers and front matter.
- **Header/footer page:** The number printed at the top or bottom of the PDF page.
- **Printed book reference:** The original book page number shown in the margin.

Example: PDF file page: 818 · Header/footer page: 768 · Printed book reference: 358

Printed book references are observed on the cited PDF pages and may not pinpoint
every word of a passage. Roman numerals, ranges, numbering resets, and multiple
references are preserved. Missing numbers are not guessed; image-only or
unreadable numbering remains unavailable. No OCR or PDF rescanning is performed
by this packaging operation.

Pagination covers {pagination['page_count']:,} PDF file pages. Header/footer
numbers are verified on {coverage.get('pdf_edition_verified', 0):,} pages;
printed book references occur on {coverage.get('original_book_verified', 0):,}
pages. Header/footer numbering is unavailable on
{coverage.get('pdf_edition_unavailable', 0):,} pages. These categories overlap.
Verified means embedded-text labels checked against reviewed layout rules, not
manual inspection of every page. Labels and descriptions are stored in the
manifest. Existing record field names remain compatible.

## Preservation and exclusions

Packaging copies the existing evidence snapshot without regenerating it.
Evidence IDs, text, attribution, concordances, schema version, builder version,
and source snapshot timestamp are preserved as supplied. The packaging date
does not replace the evidence-generation timestamp. The accompanying release
manifest records comparisons with the previous local release, including any
explicitly authorized data changes.

Original PDFs, Python source, private caches, backups, audit reports, temporary
files, SQLite databases, and application installers are excluded.

## Rights

Generated content remains subject to the rights applicable to each source
edition. Consult the source repository's third-party and CCEL notices before
redistribution. Source repository:
https://github.com/zjuerc/christianity_knowledge_base
"""


def verify_archive(archive_path, inventory, manifest, extraction_dir):
    expected = {row["name"]: row for row in inventory}
    with zipfile.ZipFile(archive_path) as archive:
        actual = archive.infolist()
        if len(actual) != len(expected) or {item.filename for item in actual} != set(expected):
            raise ValueError("ZIP member list is missing files or contains duplicates/extras")
        for item in actual:
            name = safe_name(item.filename)
            wanted = expected[name]
            if item.is_dir() or item.compress_type != zipfile.ZIP_DEFLATED:
                raise ValueError(f"Unexpected ZIP member format: {name}")
            target = extraction_dir / name
            with archive.open(item) as src, target.open("xb") as dst:
                digest = hashlib.sha256()
                for chunk in iter(lambda: src.read(1024 * 1024), b""):
                    digest.update(chunk)
                    dst.write(chunk)
            # Reading to EOF also validates the member's ZIP CRC32.
            if item.file_size != wanted["size_bytes"] or digest.hexdigest() != wanted["sha256"]:
                raise ValueError(f"ZIP member content mismatch: {name}")
    extracted = read_json(extraction_dir / "christian_kb_manifest.json")
    if extracted != manifest:
        raise ValueError("Bundled manifest differs from the source manifest")
    errors = page_locations.validate_extension(extraction_dir, extracted)
    if errors:
        raise ValueError("Extracted pagination failed validation: " + ", ".join(errors))


def smoke_test(kb_dir, extraction_dir):
    # Add only the three search runtime scripts to the disposable test checkout,
    # after the data-only archive itself has already been verified. Imports and
    # registries then resolve entirely inside this isolated extraction.
    for name in ("search_kb.py", "kb_common.py", "page_locations.py"):
        shutil.copyfile(kb_dir / name, extraction_dir / name)
    code = """
import contextlib, io, json, sys
from pathlib import Path
root = Path(sys.argv[1]).resolve()
sys.path.insert(0, str(root))
import search_kb
assert search_kb.KB_DIR == root
assert not (root / '_source_cache').exists()
assert not (root / '_pagination_cache').exists()
assert not (root.parent / 'raw_documents').exists()
catalog = search_kb.common.iter_jsonl(root / 'christian_kb_term_catalog.jsonl')
term = next(row['lookup_form'] for row in catalog if row.get('lookup_form'))
capture = io.StringIO()
with contextlib.redirect_stdout(capture):
    result = search_kb.main(['--term', term, '--layer', 'all', '--role', 'all', '--limit', '1', '--jsonl'])
rows = [json.loads(line) for line in capture.getvalue().splitlines() if line.strip()]
assert result == 0 and rows and rows[0].get('evidence_id')
assert rows[0].get('page_locations')
for location in rows[0]['page_locations']:
    assert isinstance(location['pdf_page_number'], int)
print(json.dumps({'term': term, 'evidence_id': rows[0]['evidence_id'], 'locations': len(rows[0]['page_locations'])}))
"""
    result = subprocess.run([sys.executable, "-I", "-c", code, str(extraction_dir)],
                            cwd=extraction_dir.parent, capture_output=True, text=True,
                            encoding="utf-8", timeout=180)
    if result.returncode:
        raise ValueError("Extracted KB lookup failed: " + result.stderr.strip())
    return json.loads(result.stdout)


def build_release(kb_dir, release_date, *, allow_data_changes=False):
    date.fromisoformat(release_date)
    if date.fromisoformat(release_date).isoformat() != release_date:
        raise ValueError("Use release date YYYY-MM-DD")
    kb_dir = Path(kb_dir).resolve()
    manifest = read_json(kb_dir / "christian_kb_manifest.json")
    names = select_files(kb_dir, manifest)
    if not manifest.get("pagination") or manifest["pagination"].get("display_labels") != page_locations.DISPLAY_LABELS:
        raise ValueError("Current pagination metadata and approved label descriptions are required")
    errors = page_locations.validate_extension(kb_dir, manifest)
    if errors:
        raise ValueError("Source pagination failed validation: " + ", ".join(errors))
    release_dir = kb_dir / "release"
    release_dir.mkdir(exist_ok=True)
    basename = f"christian_kb_{release_date}"
    outputs = [release_dir / (basename + suffix) for suffix in (".zip", ".zip.sha256", "_release_manifest.json")]
    if any(path.exists() for path in outputs):
        raise FileExistsError("Release already exists; refusing to overwrite: " + basename)
    previous = previous_release(release_dir, release_date)
    previous_files = {}
    previous_protected = {}
    if previous:
        _, previous_path, previous_manifest = previous
        previous_files = {item["name"]: item for item in previous_manifest["archive_members"]}
        old_zip = release_dir / previous_manifest["archive_file"]
        if old_zip.name != previous_manifest["archive_file"]:
            raise ValueError("Unsafe previous archive filename")
        for path in (previous_path, old_zip, old_zip.with_suffix(".zip.sha256")):
            if path.exists():
                previous_protected[path] = digest_file(path)
        if old_zip.exists() and previous_protected[old_zip] != previous_manifest["archive_sha256"]:
            raise ValueError("Previous archive does not match its release manifest")
        if not allow_data_changes:
            for field in SOURCE_DATE_FIELDS:
                if previous_manifest.get(field) != manifest.get(field):
                    raise ValueError(f"Source {field} changed; review before using --allow-data-changes")
    print(f"Checking {len(names)} existing files and pagination metadata...", flush=True)
    inventory = [{"name": name, "size_bytes": (kb_dir / name).stat().st_size,
                  "sha256": digest_file(kb_dir / name)} for name in names]
    permitted_updates = {"christian_kb_manifest.json", RELEASE_README}
    changed = [row["name"] for row in inventory if row["name"] in previous_files
               and row["name"] not in permitted_updates and row["sha256"] != previous_files[row["name"]]["sha256"]]
    removed = sorted(set(previous_files) - set(names) - {RELEASE_README})
    if not allow_data_changes and (changed or removed):
        raise ValueError(f"Existing data changed or disappeared: {changed + removed}")
    readme = release_readme(release_date, manifest).encode("utf-8")
    inventory.append({"name": RELEASE_README, "size_bytes": len(readme), "sha256": hashlib.sha256(readme).hexdigest()})
    inventory.sort(key=lambda row: row["name"])
    with tempfile.TemporaryDirectory(prefix=".packaging-", dir=release_dir) as temporary:
        stage = Path(temporary)
        archive_path = stage / outputs[0].name
        print(f"Compressing {len(inventory)} data/support files (DEFLATE level 6)...", flush=True)
        with zipfile.ZipFile(archive_path, "w", compression=zipfile.ZIP_DEFLATED,
                             compresslevel=6, allowZip64=True) as archive:
            for index, row in enumerate(inventory, 1):
                if row["name"] == RELEASE_README:
                    archive.writestr(RELEASE_README, readme)
                else:
                    archive.write(kb_dir / row["name"], arcname=row["name"])
                if index % 25 == 0:
                    print(f"Archived {index}/{len(inventory)} files", flush=True)
        extraction_dir = stage / "smoke_workspace" / "knowledge_base"
        extraction_dir.mkdir(parents=True)
        print("Reopening ZIP; checking every member's CRC/SHA-256 and extracting for a lookup...", flush=True)
        verify_archive(archive_path, inventory, manifest, extraction_dir)
        smoke = smoke_test(kb_dir, extraction_dir)
        print("Extracted KB lookup passed: " + smoke["evidence_id"], flush=True)
        # Detect concurrent source changes and protect the original release.
        for row in inventory:
            if row["name"] != RELEASE_README and digest_file(kb_dir / row["name"]) != row["sha256"]:
                raise ValueError("Source changed during packaging: " + row["name"])
        for path, expected in previous_protected.items():
            if digest_file(path) != expected:
                raise ValueError("Previous release changed during packaging: " + path.name)
        release = {
            "release_name": basename, "release_date": release_date,
            "source_manifest": "christian_kb_manifest.json",
            **{field: manifest[field] for field in SOURCE_DATE_FIELDS},
            "archive_file": outputs[0].name, "archive_size_bytes": archive_path.stat().st_size,
            "archive_sha256": digest_file(archive_path), "archive_member_count": len(inventory),
            "archive_members": inventory, "excluded": EXCLUDED,
            "pagination": manifest["pagination"],
            "verification": {"member_crc_and_sha256": "pass", "source_files_unchanged": True,
                             "previous_release_unchanged": True, "extracted_lookup": smoke,
                             "changed_previous_data_files": changed, "removed_previous_files": removed,
                             "comparison_release": previous[2]["release_name"] if previous else None},
        }
        (stage / outputs[1].name).write_text(release["archive_sha256"] + "  " + outputs[0].name + "\n", encoding="ascii")
        (stage / outputs[2].name).write_text(json.dumps(release, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        if any(path.exists() for path in outputs):
            raise FileExistsError("Release target appeared during packaging; refusing overwrite")
        # Windows rename refuses existing destinations; on POSIX use exclusive
        # hard links so a concurrent release can never be overwritten either.
        published = []
        try:
            for target in outputs:
                if os.name == "nt":
                    os.rename(stage / target.name, target)
                else:
                    os.link(stage / target.name, target)
                published.append(target)
        except Exception:
            for target in published:
                target.unlink()
            raise
    print(f"Created verified release: {outputs[0]} ({release['archive_size_bytes']:,} bytes)", flush=True)
    return release


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--release-date", required=True, help="Packaging date, YYYY-MM-DD; does not change the evidence timestamp")
    parser.add_argument("--kb-dir", type=Path, default=Path(__file__).resolve().parent)
    parser.add_argument("--allow-data-changes", action="store_true", help="Allow reviewed corpus changes relative to the previous release")
    args = parser.parse_args()
    try:
        build_release(args.kb_dir, args.release_date, allow_data_changes=args.allow_data_changes)
    except (OSError, ValueError, zipfile.BadZipFile, subprocess.TimeoutExpired) as exc:
        parser.exit(2, f"Release packaging stopped: {exc}\n")


if __name__ == "__main__":
    main()
